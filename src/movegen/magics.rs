#[derive(Clone, Copy, Default)]
pub struct Magic {
    pub mask: Bitboard,
    pub shift: u64,
    pub offset: u64,
    pub number: u64,
}

impl Magic {
    pub(super) fn get_index(&self, occupancy: Bitboard) -> usize {
        let relevant_blockers = occupancy & self.mask;
        let hashed = relevant_blockers.wrapping_mul(Bitboard::new(self.number));
        let index = (hashed >> self.shift).idx();
        index + self.offset as usize
    }
}
